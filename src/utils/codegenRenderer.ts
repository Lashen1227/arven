import type { ArvenConfig } from '../types.js';

export type CodegenFormat = 'zod' | 'ts';

/**
 * Map an env var name + contract to a Zod chain string.
 *
 * Rules:
 *  - SECRET vars  → z.string().min(1)            (no example leakage)
 *  - NUMBER vars  → preprocess empty strings, then coerce numbers (PORT, TIMEOUT, …)
 *  - BOOLEAN vars → z.enum(['true','false']) …    (ENABLE_FEATURE, …)
 *  - URL vars     → z.string().url()              (*_URL, *_URI)
 *  - optional     → .optional() suffix when required === false
 */
function zodChain(
  name: string,
  contract: { required?: boolean; secret?: boolean; example?: string } = {},
): string {
  const optional = contract.required === false;

  // Infer type from name or example value
  let chain: string;

  if (isNumberVar(name)) {
    const numberSchema = optional ? 'z.coerce.number().optional()' : 'z.coerce.number()';
    chain = `z.preprocess((value) => value === '' ? undefined : value, ${numberSchema})`;
  } else if (isBooleanVar(name)) {
    chain = optional
      ? "z.enum(['true', 'false']).optional()"
      : "z.enum(['true', 'false'])";
  } else if (isUrlVar(name)) {
    chain = optional ? 'z.string().url().optional()' : 'z.string().url()';
  } else {
    // Plain string — secrets and everything else
    chain = optional ? 'z.string().optional()' : 'z.string().min(1)';
  }

  return chain;
}

function isNumberVar(name: string): boolean {
  return /^(?:(?:PORT|TIMEOUT|RETRY|LIMIT|WORKERS|CONCURRENCY|TTL|EXPIRES?_IN|CACHE_TTL)(?:_|$)|(?:MAX|MIN|POOL|RATE)_)/.test(name)
    || /_PORT$/.test(name);
}

function isBooleanVar(name: string): boolean {
  return /^(ENABLE_|DISABLE_|USE_|IS_)/.test(name);
}

function isUrlVar(name: string): boolean {
  return /(URL|URI|ENDPOINT|DSN)$/.test(name);
}

/**
 * Generate a Zod-based env validator module.
 */
export function renderZodOutput(
  varNames: string[],
  config: ArvenConfig,
  categories: Map<string, string[]>,
): string {
  const lines: string[] = [
    '// Generated by arven — do not edit manually.',
    '// Re-generate with: arven codegen --overwrite',
    '//',
    '// This module validates all environment variables at application startup.',
    '// Import `env` instead of accessing process.env directly for type safety.',
    '',
    "import { z } from 'zod';",
    '',
    'const _schema = z.object({',
  ];

  const sorted = [...varNames].sort();

  // Group by category for comments inside the schema
  const nameToCategory = new Map<string, string>();
  for (const [cat, vars] of categories) {
    for (const v of vars) nameToCategory.set(v, cat);
  }

  let lastCategory = '';
  for (const name of sorted) {
    const category = nameToCategory.get(name) ?? 'General';
    if (category !== lastCategory) {
      if (lastCategory !== '') lines.push('');
      lines.push(`  // ${category}`);
      lastCategory = category;
    }

    const contract = config.variables[name] ?? {};
    const chain = zodChain(name, contract);
    const desc = contract.description ? ` // ${contract.description.replace(/\r\n|[\r\n\u2028\u2029]/g, ' ')}` : '';
    const padding = Math.max(1, 36 - name.length);
    lines.push(`  ${name}:${' '.repeat(padding)}${chain},${desc}`);
  }

  lines.push('});');
  lines.push('');
  lines.push('/**');
  lines.push(' * Validated, type-safe environment variables.');
  lines.push(' * Throws a descriptive ZodError at startup if any required variable is missing or invalid.');
  lines.push(' */');
  lines.push('export const env = _schema.parse(process.env);');
  lines.push('');
  lines.push('/** TypeScript type inferred from the Zod schema. */');
  lines.push('export type Env = z.infer<typeof _schema>;');
  lines.push('');

  return lines.join('\n');
}

/**
 * Generate a plain TypeScript validator (no external dependencies).
 * Uses a hand-rolled validate() that exits with a clear message on failure.
 */
export function renderTsOutput(
  varNames: string[],
  config: ArvenConfig,
  categories: Map<string, string[]>,
): string {
  const lines: string[] = [
    '// Generated by arven — do not edit manually.',
    '// Re-generate with: arven codegen --format ts --overwrite',
    '//',
    '// Zero-dependency env validator. Validates at startup and throws on failure.',
    '',
  ];

  // Build interface
  lines.push('export interface Env {');
  const sorted = [...varNames].sort();
  for (const name of sorted) {
    const contract = config.variables[name] ?? {};
    const optional = contract.required === false;
    const tsType = isNumberVar(name) ? 'number' : 'string';
    const padding = Math.max(1, 36 - name.length);
    lines.push(`  ${name}:${' '.repeat(padding)}${tsType}${optional ? ' | undefined' : ''};`);
  }
  lines.push('}');
  lines.push('');

  // Build validator
  lines.push('function validateEnv(): Env {');
  lines.push('  const missing: string[] = [];');
  lines.push('  const invalid: string[] = [];');
  lines.push('');

  const nameToCategory = new Map<string, string>();
  for (const [cat, vars] of categories) {
    for (const v of vars) nameToCategory.set(v, cat);
  }

  let lastCat = '';
  for (const name of sorted) {
    const cat = nameToCategory.get(name) ?? 'General';
    if (cat !== lastCat) {
      if (lastCat !== '') lines.push('');
      lines.push(`  // ${cat}`);
      lastCat = cat;
    }
    const contract = config.variables[name] ?? {};
    const optional = contract.required === false;
    if (!optional) lines.push(`  if (process.env.${name} === undefined || process.env.${name} === '') missing.push('${name}');`);
    if (isNumberVar(name)) {
      lines.push(`  const _${name} = process.env.${name} === undefined || process.env.${name} === '' ? undefined : Number(process.env.${name});`);
      lines.push(`  if (_${name} !== undefined && !Number.isFinite(_${name})) invalid.push('${name}');`);
    }
  }

  lines.push('');
  lines.push('  if (missing.length > 0 || invalid.length > 0) {');
  lines.push('    if (missing.length > 0) console.error(\'\\n[arven] Missing required environment variables:\\n\');');
  lines.push('    for (const v of missing) console.error(`  ✗ ${v}`);');
  lines.push('    if (invalid.length > 0) console.error(\'\\n[arven] Invalid numeric environment variables:\\n\');');
  lines.push('    for (const v of invalid) console.error(`  ✗ ${v} must be a finite number`);');
  lines.push('    console.error(\'\\nCheck your environment variables and try again.\\n\');');
  lines.push('    process.exit(1);');
  lines.push('  }');
  lines.push('');
  lines.push('  return {');
  for (const name of sorted) {
    lines.push(isNumberVar(name) ? `    ${name}: _${name},` : `    ${name}: process.env.${name},`);
  }
  lines.push('  } as Env;');
  lines.push('}');
  lines.push('');
  lines.push('/**');
  lines.push(' * Validated, type-safe environment variables.');
  lines.push(' * Exits with a clear error message if any required variable is missing.');
  lines.push(' */');
  lines.push('export const env = validateEnv();');
  lines.push('');

  return lines.join('\n');
}
